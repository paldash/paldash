def mutation_passives() -> list[dict[str, Any]]:
    """
    The passives the game flags with `AddMutationPal`, with their own prose.

    Five of the 1,897, and the flag is read rather than the id prefix for a
    reason worth keeping: four are named `MutationPal_*` and the fifth is
    `RideJumpCount_Increase2` (Skymarcher). **The column therefore carries
    information the naming convention does not**, which is what makes it a data
    column rather than a rule anybody could have derived from ids.

    **WHAT THE FLAG MEANS IS NOT CLAIMED.** "These can appear on a mutated Pal"
    fits the ids and the binary's `MutationPalAssignableSkillMap`, and no game
    file states it. Callers present the flag and the game's own descriptions —
    never a rate, and never as a drop table. There is no per-species mutation
    data anywhere: every term the binary names is `Combi_*`, i.e. the breeding
    system keyed on the parents' rank and IVs, and those values are native
    defaults this project cannot read.

    Sorted by id so the order is stable across regenerations.
    """
    flagged = {
        key for key, entry in (passive_effects_all() or {}).items()
        if isinstance(entry, dict) and entry.get("addMutationPal")
    }
    if not flagged:
        return []

    out: list[dict[str, Any]] = []
    # Walk the CATALOGUE, not the effects bundle: the latter is keyed lowercase
    # for case-insensitive lookup, and the API speaks canonical ids everywhere.
    for passive_id in sorted((load() or {}).get("passives") or {}):
        if str(passive_id).lower() not in flagged:
            continue
        # `describe_passive` already resolves name, prose and the `known` flag.
        # Reimplementing that is a second lookup path to drift from the first.
        entry = describe_passive(passive_id)
        effects = (passive_effects(passive_id) or {}).get("effects") or []
        entry["effects"] = effects

        # **THE PROSE IS BROKEN ON THREE OF THE FIVE**, carrying a literal
        # `{EffectValue1}` the archive never substituted — a documented defect
        # in this data, not a decode failure.
        #
        # DO NOT SUBSTITUTE FROM `effects` BY INDEX. That list skips unused and
        # zero-valued slots, so `effects[0]` is not necessarily `EffectValue1`;
        # filling the placeholder from it would print a real number in the wrong
        # place, which reads as fact. The structured effects travel instead and
        # the caller renders those.
        if "{EffectValue" in (entry.get("description") or ""):
            entry["descriptionIncomplete"] = True
        out.append(entry)
    return out


def effigy_kind_name(kind: str) -> str:
    """
    A blueprint class like `BP_LevelObject_Relic_SheepBall` -> "Lamball Effigy".

    THE SUFFIX IS A SPECIES ID, WHICH IS WHY THIS IS NOT A STRING TIDY-UP.
    The map's generic `prettyClass` helper turned these into "Relic Sheep Ball"
    and "BP Relic Object" — de-underscored game-file names shown to players in
    the effigy filter list. Splitting the words is not the same as knowing what
    they mean: `SheepBall` is the internal id for **Lamball**, and only
    `gamedata.pal_name` knows that.

    Resolution is deliberately through `pal_name`, so the case-insensitivity
    applies. The upstream ids are inconsistently capitalised — the extraction
    yields `SheepBall` while the Pal table spells it `Sheepball` — and an exact
    match would silently fall through to the raw name for exactly the entries
    this exists to fix.

    Unrecognised suffixes fall back to a humanised form rather than failing.

    **THE RULE IS VERIFIED AGAINST THE GAME'S OWN ITEM NAMES, NOT MERELY
    PLAUSIBLE.** The catalogue ships thirteen effigy items — `Relic` plus
    `Relic_01`..`Relic_12` — and the suffix rule reproduces **9 of 9** of the
    placed classes' names exactly: `…_IceCrocodile` gives "Munchill Effigy",
    which is what `Relic_03` is called. Building a name out of a class-name
    suffix is the kind of thing that reads right and is wrong, so the agreement
    is the evidence rather than the reasoning.

    **The two unsuffixed classes were rendering as bare "Effigy" — 155 of 396,
    which is why they read as data that had failed to load.** They are the plain
    relic, and the game's own name for the plain relic is `Relic` -> "Lifmunk
    Effigy". Resolved through the catalogue rather than hardcoded, so a
    localisation change carries and a missing bundle degrades to "Effigy"
    instead of to a stale English string.

    Three catalogue entries — Lunaris, Relaxaurus and Mimog — have no placed
    class at all. Not a gap here: nothing in the world references them.
    """
    if not kind:
        return "Effigy"

    for prefix in ("BP_LevelObject_Relic_", "BP_RelicObject_"):
        if kind.startswith(prefix):
            species = kind[len(prefix):]
            return f"{pal_name(species)} Effigy" if species else "Effigy"

    if kind in ("BP_LevelObject_Relic", "BP_RelicObject"):
        plain = item_name("Relic")
        # `item_name` echoes the id back when the catalogue has no row, and
        # "Relic" is not a name to show anybody.
        return plain if plain and plain != "Relic" else "Effigy"
    return f"{humanize(kind)} Effigy"


_effigy_icon_index: Optional[dict[str, str]] = None


def effigy_kind_icon(kind: str) -> str:
    """
    The game's own artwork for one effigy class, or `""`.

    The map drew all 396 effigies as one generic shape while the thirteen relic
    icons — `T_itemicon_Relic_01`..`_12` plus the plain one — were already
    installed by `install-icons.py` and going unused.

    **Joined on the NAME, which is the join the test suite already validates.**
    A class carries a species suffix and an item carries a number, and nothing
    connects `…_IceCrocodile` to `Relic_03` directly — but both resolve to
    "Munchill Effigy", and `test_effigy_names.py` asserts all ten placed classes
    land on a name the item table actually ships. So this reuses a correspondence
    that is already pinned rather than inventing a second mapping that could
    disagree with the first.

    Returns `""` rather than a placeholder when the name does not match an item,
    so the caller keeps its existing shape. That is the whole degradation path:
    an effigy with no icon is drawn exactly as all 396 were before.
    """
    global _effigy_icon_index
    if _effigy_icon_index is None:
        index: dict[str, str] = {}
        for item_id in ["Relic"] + [f"Relic_{n:02d}" for n in range(1, 13)]:
            entry = _lookup("items", item_id) or {}
            name = entry.get("name")
            icon = entry.get("icon")
            if name and icon:
                index[str(name).casefold()] = str(icon)
        _effigy_icon_index = index

    return _effigy_icon_index.get(effigy_kind_name(kind).casefold(), "")


def fast_travel_kind(name: str) -> str:
    """
    `tower`, `watchtower` or `travel` for one fast-travel point.

    **The tower bosses are already in this table and nothing said so.** All 174
    points rendered as one identical gold marker, so "where are the towers" had
    no answer on a map that was in fact showing all eight of them — the eight
    named `… Tower Entrance`. Splitting the layer by kind was the fix; extracting
    anything new from the pak was not needed and would have been the wrong tree.

    Classified from the localized name rather than from an id, because the name
    is the only field that distinguishes them — the keys are opaque hex. That
    means this is **English-dependent**, and it fails to the safe side: an
    unrecognised name is a plain travel point, which is what every point was
    before this existed.

    The distinction matters because they are different things: a Tower Entrance
    is a boss arena you clear once, a Watchtower is scenery with a statue at the
    bottom, and neither is the other.
    """
    lowered = name.lower()
    if lowered.endswith("tower entrance"):
        return "tower"
    if "watchtower" in lowered:
        return "watchtower"
    return "travel"


def fast_travel_points() -> list[dict[str, Any]]:
    """
    All 174 fast-travel points with world coordinates and localized names.

    Coordinates share the save's world space, so they feed the existing map
    transform unchanged. Covers both landmasses — 17 of these sit on the World
    Tree side.

    Measured split: **8 tower entrances, 22 watchtowers, 144 ordinary points** —
    and the eight are exactly Palworld's eight tower bosses, which is the check
    that the name rule is picking out the right thing rather than merely
    something.
    """
    return [
        {"key": key, "kind": fast_travel_kind(str(value.get("name") or "")), **value}
        for key, value in sorted(load().get("fastTravel", {}).items())
    ]


