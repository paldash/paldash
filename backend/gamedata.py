# ─── World data ──────────────────────────────────────────────────


def effigies() -> list[dict[str, Any]]:
    """
    All 396 effigies, each with world coordinates **and its instance GUID**.

    The GUID is the useful part. A save's `RelicObtainForInstanceFlag` keys on
    exactly these values, so a player's collected set joins directly against
    this list — which is what makes "show me the ones I have not found" possible
    rather than just "here are all of them".

    Extracted from the game pak by `scripts/extract-effigies.py`; every position
    is verified to land in a streaming cell the game ships content for, and
    every effigy the reference world's players had collected (37 of 37) appears
    here. Returns an empty list rather than raising if the bundle is absent, so
    a missing file degrades the map instead of breaking it.
    """
    global _effigies
    if _effigies is not None:
        return _effigies

    try:
        with gzip.open(EFFIGY_PATH, "rt", encoding="utf-8") as f:
            _effigies = json.load(f).get("effigies") or []
    except (OSError, json.JSONDecodeError) as e:
        logger.warning("Effigy data unavailable (%s); the map will omit them", e)
        _effigies = []

    for effigy in _effigies:
        effigy["kindName"] = effigy_kind_name(str(effigy.get("kind") or ""))
    return _effigies


def passive_effects(passive_id: str) -> Optional[dict[str, Any]]:
    """
    The *numeric* effects of one passive skill, or None if it is not bundled.

    The `passives` section of `gamedata.json.gz` carries a **sentence** —
    "Attack +5%" — which is right for showing a player and useless for computing
    anything. This is `DT_PassiveSkill_Main` out of the server pak, extracted by
    `scripts/extract-passive-effects.py`:

        {"rank": 4,
         "effects": [{"type": "ShotAttack", "value": 20.0, "target": "ToSelf"},
                     {"type": "Defense",    "value": 20.0, "target": "ToSelf"}],
         "invoke": ["InvokeAlways"], "lotteryWeight": 10, "element": ""}

    VERIFIED AGAINST THE GAME'S OWN PROSE: of the 1,897 bundled passives, 1,754
    have a numeric English description and **1,754 match**, on 5 exceptions —
    four of which are the PST archive's descriptions failing to substitute their
    own `{EffectValue1}` placeholder, so the table is right and the sentence is
    broken. The remaining one (`FullStomach_Down_1_BossDefeat`, prose "+10.0%
    slower" against a stored -1.0) is a real disagreement and is not resolved.

    Case-insensitive like every other lookup here, for the reason the module
    docstring gives.
    """
    global _passive_effects
    if _passive_effects is None:
        try:
            with gzip.open(PASSIVE_EFFECT_PATH, "rt", encoding="utf-8") as f:
                raw = json.load(f)
            _passive_effects = {str(k).lower(): v for k, v in raw.items()}
        except (OSError, json.JSONDecodeError) as e:
            # Degrade rather than raise: without this bundle a stat simply
            # carries no passive term, which is exactly what it did before the
            # bundle existed. A missing file must not take out /api/pals.
            logger.warning(
                "Passive effect data unavailable (%s); stats will omit the "
                "passive term", e,
            )
            _passive_effects = {}
    return _passive_effects.get(str(passive_id or "").lower())


def effigy_kind_name(kind: str) -> str:
    """
    A blueprint class like `BP_LevelObject_Relic_SheepBall` -> "Lamball Effigy".

    THE SUFFIX IS A SPECIES ID, WHICH IS WHY THIS IS NOT A STRING TIDY-UP.
    The map's generic `prettyClass` helper turned these into "Relic Sheep Ball"
    and "BP Relic Object" — de-underscored game-file names shown to players in
    the effigy filter list. Splitting the words is not the same as knowing what
    they mean: `SheepBall` is the internal id for **Lamball**, and only
    `gamedata.pal_name` knows that.

    Resolution is deliberately through `pal_name`, so the case-insensitivity
    applies. The upstream ids are inconsistently capitalised — the extraction
    yields `SheepBall` while the Pal table spells it `Sheepball` — and an exact
    match would silently fall through to the raw name for exactly the entries
    this exists to fix.

    Unrecognised suffixes fall back to a humanised form rather than failing, and
    the two unsuffixed classes (`BP_LevelObject_Relic`, `BP_RelicObject` — 155 of
    the 396 between them) are plain "Effigy", because they genuinely are not
    tied to a species.
    """
    if not kind:
        return "Effigy"

    for prefix in ("BP_LevelObject_Relic_", "BP_RelicObject_"):
        if kind.startswith(prefix):
            species = kind[len(prefix):]
            return f"{pal_name(species)} Effigy" if species else "Effigy"

    if kind in ("BP_LevelObject_Relic", "BP_RelicObject"):
        return "Effigy"
    return f"{humanize(kind)} Effigy"


def fast_travel_kind(name: str) -> str:
    """
    `tower`, `watchtower` or `travel` for one fast-travel point.

    **The tower bosses are already in this table and nothing said so.** All 174
    points rendered as one identical gold marker, so "where are the towers" had
    no answer on a map that was in fact showing all eight of them — the eight
    named `… Tower Entrance`. Splitting the layer by kind was the fix; extracting
    anything new from the pak was not needed and would have been the wrong tree.

    Classified from the localized name rather than from an id, because the name
    is the only field that distinguishes them — the keys are opaque hex. That
    means this is **English-dependent**, and it fails to the safe side: an
    unrecognised name is a plain travel point, which is what every point was
    before this existed.

    The distinction matters because they are different things: a Tower Entrance
    is a boss arena you clear once, a Watchtower is scenery with a statue at the
    bottom, and neither is the other.
    """
    lowered = name.lower()
    if lowered.endswith("tower entrance"):
        return "tower"
    if "watchtower" in lowered:
        return "watchtower"
    return "travel"


def fast_travel_points() -> list[dict[str, Any]]:
    """
    All 174 fast-travel points with world coordinates and localized names.

    Coordinates share the save's world space, so they feed the existing map
    transform unchanged. Covers both landmasses — 17 of these sit on the World
    Tree side.

    Measured split: **8 tower entrances, 22 watchtowers, 144 ordinary points** —
    and the eight are exactly Palworld's eight tower bosses, which is the check
    that the name rule is picking out the right thing rather than merely
    something.
    """
    return [
        {"key": key, "kind": fast_travel_kind(str(value.get("name") or "")), **value}
        for key, value in sorted(load().get("fastTravel", {}).items())
    ]


def fast_travel_name(point_id: str) -> str:
    entry = _lookup("fastTravel", point_id)
    return entry["name"] if entry else humanize(point_id)


def work_suitabilities() -> list[dict[str, Any]]:
    return load().get("workSuitability", [])


# ─── Reference totals ────────────────────────────────────────────


def totals() -> dict[str, Any]:
    """
    Exact Palworld 1.0 figures, computed from the game's own data tables.

    These replace the previously web-sourced estimates. Notably: 1,413 ordinary
    technology points across 537 technologies, and 185 ancient technology points
    across 51 boss technologies.
    """
    return dict(load().get("totals", {}))
