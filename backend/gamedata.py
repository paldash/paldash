class GameDataUnavailable(Exception):
    """Raised when the bundled reference data is missing or unreadable."""


# ─── Loading ─────────────────────────────────────────────────────


def load() -> dict[str, Any]:
    """Load and cache the bundle. Cheap after the first call (~215 KB gzipped)."""
    global _data
    if _data is not None:
        return _data

    if not os.path.exists(DATA_PATH):
        raise GameDataUnavailable(
            f"Game data not found at {DATA_PATH}. "
            "Run: python3 scripts/build-gamedata.py"
        )

    try:
        with gzip.open(DATA_PATH, "rt", encoding="utf-8") as f:
            _data = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        raise GameDataUnavailable(f"Could not read {DATA_PATH}: {e}") from e

    logger.info(
        "Loaded game data: %d items, %d pals, %d technologies",
        len(_data.get("items", {})),
        len(_data.get("pals", {})),
        len(_data.get("technology", {})),
    )
    return _data


def available() -> bool:
    """Whether reference data is usable. Never raises — for health checks."""
    try:
        load()
        return True
    except GameDataUnavailable:
        return False


def _index(section: str) -> dict[str, Any]:
    """Case-insensitive index for one section, built once."""
    if section not in _indexes:
        entries = load().get(section, {})
        _indexes[section] = {key.lower(): value for key, value in entries.items()}
    return _indexes[section]


def _lookup(section: str, key: str) -> Optional[dict]:
    if not key:
        return None
    return _index(section).get(str(key).lower())


def _reset_cache() -> None:
    """
    Test hook — drops **every** module-level cache.

    It used to drop only `_data` and `_effigies`, so a test pointing
    `BOSS_SPAWNER_DATA_PATH` or `PASSIVE_EFFECT_DATA_PATH` at a fixture got
    whatever the previous test had loaded. Each bundle added since arrived with
    its own global and none were added here, which is the failure mode a partial
    reset always has: it works until it silently does not.
    """
    global _data, _effigies, _passive_effects, _game_settings
    global _boss_spawners, _work_assign, _basecamp, _economy, _spawns, _moves
    global _npcs, _guild
    global _progression, _raidbosses, _invaders, _worldpresets
    # Derived from `_boss_spawners`, so it has to go with it — a stale index
    # would keep answering from the bundle that was just replaced.
    global _boss_level_index
    _boss_level_index = None
    _data = None
    _effigies = None
    _passive_effects = None
    _game_settings = None
    _boss_spawners = None
    _work_assign = None
    _basecamp = None
    _economy = None
    _npcs = None
    _guild = None
    _spawns = None
    _moves = None
    _progression = None
    _raidbosses = None
    _invaders = None
    _worldpresets = None
    _indexes.clear()


def reload() -> dict[str, Any]:
    """
    Drop the cached bundles and read them again from disk.

    The counterpart to `worldobjects.reload()`, for the same reason: replacing a
    regenerated `gamedata.json.gz` or `effigies.json.gz` on disk should not need
    a container restart to take effect. Reports what loaded rather than only
    that it did.
    """
    _reset_cache()
    data = load()
    return {
        "gamedata": {
            "path": DATA_PATH,
            "loaded": bool(data),
            "items": len(data.get("items") or {}),
            "pals": len(data.get("pals") or {}),
            "technologies": len(data.get("technologies") or {}),
        },
        "effigies": {
            "path": EFFIGY_PATH,
            "count": len(effigies()),
        },
    }


# ─── Fallback naming ─────────────────────────────────────────────


def humanize(asset_id: str) -> str:
    """
    Best-effort display name for an ID with no reference entry.

    `PalEgg_Dragon` -> `Pal Egg Dragon`. Better than showing raw shorthand, and
    it makes a missing entry obvious rather than silently wrong.

    Only splits lowercase->uppercase boundaries. Adding an uppercase->uppercase
    rule would turn `NotAReal` into `Not A Real` but also `AIcore` into
    `A Icore`, and the two are structurally identical — no rule distinguishes
    them. Since anything with a reference entry never reaches this function, the
    simpler behaviour is the safer one.
    """
    if not asset_id:
        return ""
    spaced = re.sub(r"[_\-]+", " ", str(asset_id))
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", spaced)
    return " ".join(spaced.split())


