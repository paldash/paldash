_indexes: dict[str, dict[str, Any]] = {}


class GameDataUnavailable(Exception):
    """Raised when the bundled reference data is missing or unreadable."""


# ─── Loading ─────────────────────────────────────────────────────


def load() -> dict[str, Any]:
    """Load and cache the bundle. Cheap after the first call (~215 KB gzipped)."""
    global _data
    if _data is not None:
        return _data

    if not os.path.exists(DATA_PATH):
        raise GameDataUnavailable(
            f"Game data not found at {DATA_PATH}. "
            "Run: python3 scripts/build-gamedata.py"
        )

    try:
        with gzip.open(DATA_PATH, "rt", encoding="utf-8") as f:
            _data = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        raise GameDataUnavailable(f"Could not read {DATA_PATH}: {e}") from e

    logger.info(
        "Loaded game data: %d items, %d pals, %d technologies",
        len(_data.get("items", {})),
        len(_data.get("pals", {})),
        len(_data.get("technology", {})),
    )
    return _data


def available() -> bool:
    """Whether reference data is usable. Never raises — for health checks."""
    try:
        load()
        return True
    except GameDataUnavailable:
        return False


def _index(section: str) -> dict[str, Any]:
    """Case-insensitive index for one section, built once."""
    if section not in _indexes:
        entries = load().get(section, {})
        _indexes[section] = {key.lower(): value for key, value in entries.items()}
    return _indexes[section]


def _lookup(section: str, key: str) -> Optional[dict]:
    if not key:
        return None
    return _index(section).get(str(key).lower())


def _reset_cache() -> None:
    """
    Test hook — drops **every** module-level cache.

    It used to drop only `_data` and `_effigies`, so a test pointing
    `BOSS_SPAWNER_DATA_PATH` or `PASSIVE_EFFECT_DATA_PATH` at a fixture got
    whatever the previous test had loaded. Each bundle added since arrived with
    its own global and none were added here, which is the failure mode a partial
    reset always has: it works until it silently does not.
    """
    global _data, _effigies, _passive_effects, _game_settings
    global _boss_spawners, _work_assign, _basecamp, _economy
    _data = None
    _effigies = None
    _passive_effects = None
    _game_settings = None
    _boss_spawners = None
    _work_assign = None
    _basecamp = None
    _economy = None
    _indexes.clear()


def reload() -> dict[str, Any]:
    """
    Drop the cached bundles and read them again from disk.

    The counterpart to `worldobjects.reload()`, for the same reason: replacing a
    regenerated `gamedata.json.gz` or `effigies.json.gz` on disk should not need
    a container restart to take effect. Reports what loaded rather than only
    that it did.
    """
    _reset_cache()
    data = load()
    return {
        "gamedata": {
            "path": DATA_PATH,
            "loaded": bool(data),
            "items": len(data.get("items") or {}),
            "pals": len(data.get("pals") or {}),
            "technologies": len(data.get("technologies") or {}),
        },
        "effigies": {
            "path": EFFIGY_PATH,
            "count": len(effigies()),
        },
    }


# ─── Fallback naming ─────────────────────────────────────────────


def humanize(asset_id: str) -> str:
    """
    Best-effort display name for an ID with no reference entry.

    `PalEgg_Dragon` -> `Pal Egg Dragon`. Better than showing raw shorthand, and
    it makes a missing entry obvious rather than silently wrong.

    Only splits lowercase->uppercase boundaries. Adding an uppercase->uppercase
    rule would turn `NotAReal` into `Not A Real` but also `AIcore` into
    `A Icore`, and the two are structurally identical — no rule distinguishes
    them. Since anything with a reference entry never reaches this function, the
    simpler behaviour is the safer one.
    """
    if not asset_id:
        return ""
    spaced = re.sub(r"[_\-]+", " ", str(asset_id))
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", spaced)
    return " ".join(spaced.split())


# ─── Items ───────────────────────────────────────────────────────


def item(item_id: str) -> Optional[dict]:
    return _lookup("items", item_id)


def item_name(item_id: str) -> str:
    entry = item(item_id)
    return entry["name"] if entry else humanize(item_id)


def describe_item(item_id: str) -> dict[str, Any]:
    """Everything a list row or tooltip needs, with safe fallbacks."""
    entry = item(item_id) or {}
    return {
        "id": item_id,
        "name": entry.get("name") or humanize(item_id),
        "icon": entry.get("icon", ""),
        "rarity": entry.get("rarity", 0),
        "typeA": entry.get("typeA", ""),
        "typeB": entry.get("typeB", ""),
        "maxStack": entry.get("maxStack", 0),
        "weight": entry.get("weight", 0),
        "description": entry.get("description", ""),
        "known": bool(entry),
    }


def all_items() -> list[dict[str, Any]]:
    """
    The whole item catalogue — every id the game has, not the ones a world holds.

    The distinction is the bug this exists for. The slot editor's autocomplete
    was built from `/api/items`, which reports **what is in the parsed world**,
    so typing any legitimate item nobody on the server happened to own showed
    "not in this world" with no icon. The backend accepted it on preview, having
    always validated against this full catalogue — so the editor was telling
    people their input was wrong and then writing it correctly.

    `id` and `name` both travel because the API speaks ids (`AIcore`) and people
    speak names ("AI Core"), and a catalogue that carries only one of them forces
    every caller to build the other index itself.
    """
    entries = (load().get("items") or {})
    return [
        {
            "id": item_id,
            "name": entry.get("name") or humanize(item_id),
            "icon": entry.get("icon", ""),
            "rarity": entry.get("rarity", 0),
            "typeA": entry.get("typeA", ""),
            "typeB": entry.get("typeB", ""),
            "maxStack": entry.get("maxStack", 0),
            "weight": entry.get("weight", 0),
            # Present only on equipment. The editor uses it to warn *before* a
            # preview that a slot cannot be overwritten without orphaning a
            # DynamicItemSaveData record.
            "hasDurability": bool((entry.get("dynamic") or {}).get("type")),
        }
        for item_id, entry in sorted(entries.items())
    ]


def max_stack(item_id: str) -> int:
    """
    The game's real stack ceiling, or 0 if unknown.

    saveedit currently infers a ceiling from the largest stack present in the
    save. This is the authoritative figure, but swapping it in changes what a
    sort writes, so that is a deliberate change and not a drive-by one.
    """
    entry = item(item_id)
    return int(entry.get("maxStack") or 0) if entry else 0


# ─── Pals ────────────────────────────────────────────────────────


def normalise_species(species_id: str) -> tuple[str, list[str]]:
    """Strip BOSS_/PREDATOR_/etc, returning (species, prefixes_found)."""
    remaining = str(species_id or "")
    found: list[str] = []
    changed = True
    while changed:
        changed = False
        for prefix in _SPECIES_PREFIXES:
            if remaining.upper().startswith(prefix):
                found.append(prefix.rstrip("_"))
                remaining = remaining[len(prefix):]
                changed = True
    return remaining, found


def pal(species_id: str) -> Optional[dict]:
    species, _ = normalise_species(species_id)
    return _lookup("pals", species)


def pal_exact(species_id: str) -> Optional[dict]:
    """
    A species' own entry, **without** stripping `BOSS_` and friends.

    `pal()` normalises, which is right for naming — an alpha Lamball is still
    called Lamball — and wrong for anything that reads the numbers, because the
    prefixed forms carry their own, higher, stat scaling. `BOSS_Alpaca` has hp
    108 where `Alpaca` has 90, and that difference *is* the alpha bonus. Look up
    the base species and the bonus silently disappears; apply a separate boss
    multiplier on top of the base and it gets counted twice.

    Falls back to the normalised lookup, so a form present in a save but absent
    from the tables still resolves to something rather than to nothing.
    """
    return _lookup("pals", species_id) or pal(species_id)


def pal_exp_table() -> dict[str, Any]:
    """
    The game's own level -> EXP table. `{}` if the bundle is unavailable.

    Two columns per level, and picking the wrong one is easy: `PalNextEXP` is
    the Pal curve and `NextEXP` beside it is the *player* curve. They differ
    from level 2 onwards (25 vs 50).
    """
    return load().get("palExpTable") or {}


def pal_name(species_id: str) -> str:
    entry = pal(species_id)
    if entry:
        return entry["name"]
    species, _ = normalise_species(species_id)
    return humanize(species)


def describe_pal(species_id: str) -> dict[str, Any]:
    species, prefixes = normalise_species(species_id)
    entry = pal(species_id) or {}
    return {
        "id": species_id,
        "species": species,
        "name": entry.get("name") or humanize(species),
        "icon": entry.get("icon", ""),
        "elements": entry.get("elements", []),
        "rarity": entry.get("rarity", 0),
        "paldeckNumber": entry.get("zukanIndex", 0),
        "workSuitabilities": entry.get("workSuitabilities", {}),
        "variants": prefixes,
        "known": bool(entry),
    }


def npc_name(npc_id: str) -> str:
    entry = _lookup("npcs", npc_id)
    return entry["name"] if entry else humanize(npc_id)


def character(character_id: str) -> Optional[dict]:
    """
    The record for anything in CharacterSaveParameterMap, Pal or human.

    `pal()` alone answers "is this a known Pal", which is not the same question
    as "is this a known character". On the reference world 100 of the 1,905
    entries are NPCs — guards, merchants, villagers — so treating a Pal-table
    miss as "unrecognised" flags a clean world as full of modded content.
    """
    species, _ = normalise_species(character_id)
    return _lookup("pals", species) or _lookup("npcs", species)


def character_name(character_id: str) -> str:
    """
    Name for anything in CharacterSaveParameterMap.

    That map holds humans as well as Pals — merchants, guards, tower bosses — so
    a Pal-only lookup leaves a good fraction of a real world showing internal IDs
    like `Believer_CrossBow` instead of `Free Pal Alliance Believer`.
    """
    species, _ = normalise_species(character_id)
    entry = _lookup("pals", species) or _lookup("npcs", species)
    return entry["name"] if entry else humanize(species)


