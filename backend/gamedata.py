def best_work_suitability(species_id: str) -> Optional[str]:
    """
    The one work type a species is *best* at, from `DT_PalMonsterParameter`.

    **This is the per-species half of the condenser mechanic.** Raising a Pal's
    condenser rank raises its work suitability for this work type only — which
    is why the field is bundled even though the *size* of that increase is in
    none of the game's data files.

    Searched exhaustively 2026-08-05 and recorded so nobody repeats it: all 471
    server-pak DataTables, the `BP_PalGameSetting` CDO, the condenser build
    object's own CDO (pure presentation — visuals, collision, destroy FX), and
    the name tables of all **10,286** server-pak blueprints, which reference
    `BestWorkSuitability` **zero** times. A name table is plainly serialised even
    where properties are not, so that last one is decisive: the logic is in the
    binary, the same wall `elements.py` documents.

    So this returns a *fact* and no arithmetic. `optimise.work_level` still
    reports `base` + `bought` and is knowingly low for condensed Pals until the
    magnitude is measured — see task #74, which carries the sampling plan.

    Uses `pal_exact`-style resolution deliberately **not** applied here: the
    lookup is on the id as stored, then the `BOSS_`-stripped form, matching how
    `workSuitabilities` beside it behaves.

    None means the species has no best work — which is real for the handful with
    an entirely empty work table (Panthalus, Astralym) — or that the id is
    unknown. Both cases mean "do not claim a bonus applies".
    """
    entry = _lookup("pals", species_id)
    if entry is None and species_id:
        for prefix in _SPECIES_PREFIXES:
            if species_id.upper().startswith(prefix):
                entry = _lookup("pals", species_id[len(prefix):])
                break
    return (entry or {}).get("bestWorkSuitability") or None


def region_name(region_id: str) -> str:
    """
    What the game calls a map region — `Grass_1` is "Windswept Island".

    `extract-progression.py` deliberately carried `DT_WorldMapAreaData`'s
    `MsgID` unresolved rather than humanising it, because inventing "Grass 1"
    would have been a second source of truth. This is the game's own answer,
    and it is what turns the save's opaque `FindAreaFlagMap` into "47 of 123
    areas discovered".

    The stored ids carry the `REGION_` prefix off the message id; callers pass
    either form.
    """
    regions = load().get("regions") or {}
    key = region_id[len("REGION_"):] if region_id.upper().startswith("REGION_") else region_id
    index = {k.lower(): v for k, v in regions.items()}
    return index.get(key.lower()) or humanize(key)


def dungeon_name(dungeon_id: str) -> str:
    """The game's name for a dungeon — `Sealed Realm of the Frozen Wings`."""
    dungeons = load().get("dungeons") or {}
    key = dungeon_id[len("NAME_"):] if dungeon_id.upper().startswith("NAME_") else dungeon_id
    index = {k.lower(): v for k, v in dungeons.items()}
    return index.get(key.lower()) or humanize(key)


# ─── World data ──────────────────────────────────────────────────


def effigies() -> list[dict[str, Any]]:
    """
    All 396 effigies, each with world coordinates **and its instance GUID**.

    The GUID is the useful part. A save's `RelicObtainForInstanceFlag` keys on
    exactly these values, so a player's collected set joins directly against
    this list — which is what makes "show me the ones I have not found" possible
    rather than just "here are all of them".

    Extracted from the game pak by `scripts/extract-effigies.py`; every position
    is verified to land in a streaming cell the game ships content for, and
    every effigy the reference world's players had collected (37 of 37) appears
    here. Returns an empty list rather than raising if the bundle is absent, so
    a missing file degrades the map instead of breaking it.
    """
    global _effigies
    if _effigies is not None:
        return _effigies

    try:
        with gzip.open(EFFIGY_PATH, "rt", encoding="utf-8") as f:
            _effigies = json.load(f).get("effigies") or []
    except (OSError, json.JSONDecodeError) as e:
        logger.warning("Effigy data unavailable (%s); the map will omit them", e)
        _effigies = []

    for effigy in _effigies:
        effigy["kindName"] = effigy_kind_name(str(effigy.get("kind") or ""))
    return _effigies


def boss_spawners() -> list[dict[str, Any]]:
    """
    The 90 placed field bosses: species, **level** and world position.

    From `DT_BossSpawnerLoactionData` via `scripts/extract-boss-spawners.py`.
    Levels were documented as unavailable across this project for months — they
    were behind a reader refusal, not absent.

    **Positions are verified, not assumed.** All 90 land on an occupied World
    Partition cell at 25,600 units, with controls at 12,800 (22) and 51,200 (83)
    both worse. The extractor refuses to write if that stops being true.

    Empty list rather than raising when the bundle is absent, like `effigies()`:
    a missing file should cost the layer, not the map.
    """
    global _boss_spawners
    if _boss_spawners is None:
        try:
            with gzip.open(BOSS_SPAWNER_PATH, "rt", encoding="utf-8") as f:
                _boss_spawners = json.load(f).get("bosses") or []
        except (OSError, json.JSONDecodeError) as e:
            logger.warning(
                "Boss spawner data unavailable (%s); the layer will be empty", e
            )
            _boss_spawners = []
    return _boss_spawners


#: How far apart two records of the same field boss may sit and still be the
#: same field boss. **One World Partition cell**, the constant the cell grid is
#: pinned at everywhere else here — chosen because it is already established
#: rather than fitted to this join's own gap, which would be fitting the method
#: to the answer.
_SAME_BOSS = 25600.0

_boss_level_index: Optional[dict[str, list[tuple[float, float, int, str]]]] = None


def _boss_level_lookup() -> dict[str, list[tuple[float, float, int, str]]]:
    global _boss_level_index
    if _boss_level_index is None:
        index: dict[str, list[tuple[float, float, int, str]]] = {}
        for row in boss_spawners():
            species = str(row.get("speciesId") or "")
            if not species:
                continue
            index.setdefault(species, []).append(
                (float(row.get("x") or 0.0), float(row.get("y") or 0.0),
                 int(row.get("level") or 0), str(row.get("spawnerId") or ""))
            )
        _boss_level_index = index
    return _boss_level_index


def boss_level_at(species: str, x: float, y: float) -> Optional[dict[str, Any]]:
    """
    The level of the field boss standing at `(x, y)`, or None.

    **Two extractions of overlapping things, joined on POSITION rather than on
    species.** `worldobjects.json.gz` carries 99 `FBOSS` placements found by
    name-table intersection; `boss_spawners.json.gz` carries 90 rows read out of
    `DT_BossSpawnerLoactionData`, and AGENTS.md records that neither supersedes
    the other. So the popup said "level is on the other layer" — technically
    honest and useless to somebody looking at Silvegis, whose level the game's
    own map shows.

    **The join is measured, and it holds.** Of the 93 placements whose species
    appears in the boss table, **60 sit at a distance of ~0** — byte-identical
    coordinates, the same actor read two ways — and 64 fall inside one cell. The
    control is what makes that evidence: shuffle the species labels across the
    boss rows and the best of 200 trials matches **7**. A drifted or coincidental
    correspondence does not put sixty points on top of each other.

    **Species alone is NOT enough, and the data says why.** `BOSS_GrassGolem` is
    the one species with two levels (55 and 75) — so a species-keyed lookup would
    confidently hand one placement the other's level. It is also the reason
    `remainsIsland_1_GrassGolem_FBOSS` is listed twice, noted in AGENTS.md.

    The 35 placements with no match keep no level rather than borrowing one from
    the same species elsewhere: a second placement of a species genuinely can
    carry a different level, and an inferred number reads exactly like a read one.
    """
    candidates = _boss_level_lookup().get(species or "")
    if not candidates:
        return None
    best = min(candidates, key=lambda c: (c[0] - x) ** 2 + (c[1] - y) ** 2)
    distance = ((best[0] - x) ** 2 + (best[1] - y) ** 2) ** 0.5
    if distance > _SAME_BOSS:
        return None
    return {"level": best[2], "spawnerId": best[3], "distance": round(distance, 1)}


