"""
Friendly names and reference figures for Palworld 1.0.

Save files store internal asset IDs — `Sheepball`, `AIcore`, `Accessory_AirDash1`
— so every list in the dashboard used to show developer shorthand. This module
resolves those to the names players actually see, and supplies the exact
progression denominators that used to be guessed from web sources.

Data comes from `backend/data/gamedata.json.gz`, generated by
`scripts/build-gamedata.py`. It is bundled, never fetched: the container has to
work offline on a LAN.

**THE STRINGS AND THE NUMBERS BOTH COME FROM THE GAME NOW.** Numbers are the
server pak's DataTables (verified against the previous third-party catalogue,
13,836 of 13,836 values agreeing); display names and descriptions are the client
pak's `L10N/en` overrides, read by `scripts/l10n.py` and joined by
`scripts/gametext.py`. The reference archive still supplies icon paths and the
list of which ids exist, and it still names the entries the game leaves
untranslated — `build-gamedata.py` prints that count per section rather than
letting it pass as complete coverage.

LOOKUPS ARE CASE-INSENSITIVE, deliberately. The upstream data is inconsistently
capitalised — a save records `Sheepball`, `OctopusGirl` and `SwordCutlassfish`
while the reference data spells them `SheepBall`, `OctopusGIrl` and
`SwordCutlassFish`. Exact matching silently loses eight real Pals. The game's own
data has the same problem in its rich-text tags, which ship three spellings of
`mapObjectName`.

**Names the game gives are not always the ones the archive gave**, and where they
differ the game wins:

- Accessory tiers are distinct. `Accessory_AT_2` is "Attack Pendant **+1**"; the
  archive called all three tiers "Attack Pendant", so three different items
  shared one name.
- `BOSS_`/`GYM_` forms are named for the species, without the archive's `(Boss)`
  and `(Gym)` decorations. That agrees with this module's own rule that an alpha
  Lamball is still called Lamball, and `isBoss` travels separately.
"""

