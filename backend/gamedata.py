def all_items() -> list[dict[str, Any]]:
    """
    The whole item catalogue — every id the game has, not the ones a world holds.

    The distinction is the bug this exists for. The slot editor's autocomplete
    was built from `/api/items`, which reports **what is in the parsed world**,
    so typing any legitimate item nobody on the server happened to own showed
    "not in this world" with no icon. The backend accepted it on preview, having
    always validated against this full catalogue — so the editor was telling
    people their input was wrong and then writing it correctly.

    `id` and `name` both travel because the API speaks ids (`AIcore`) and people
    speak names ("AI Core"), and a catalogue that carries only one of them forces
    every caller to build the other index itself.

    **`liveTwin` is a badge, never a filter.** It names the legal item sharing
    this one's display name, so an autocomplete showing two identical rows can
    say which one the game still uses (`Gunpowder` -> `Gunpowder2`). Hiding the
    legacy id instead would be wrong: `bLegalInGame` is *not* "unobtainable" —
    ten of the 575 false ones are held in refworld right now — and the editor's
    whole job is writing ids that already exist in somebody's save.

    `legalInGame` travels for the 575 so a caller can tell "the game flags this"
    from "we have nothing to say", but only the 95 with a twin carry an
    actionable claim. See `scripts/build-gamedata.py:apply_item_legality`.
    """
    entries = (load().get("items") or {})
    out = []
    for item_id, entry in sorted(entries.items()):
        row = {
            "id": item_id,
            "name": entry.get("name") or humanize(item_id),
            "icon": entry.get("icon", ""),
            "rarity": entry.get("rarity", 0),
            "typeA": entry.get("typeA", ""),
            "typeB": entry.get("typeB", ""),
            "maxStack": entry.get("maxStack", 0),
            "weight": entry.get("weight", 0),
            # Present only on equipment. The editor uses it to warn *before* a
            # preview that a slot cannot be overwritten without orphaning a
            # DynamicItemSaveData record.
            "hasDurability": bool((entry.get("dynamic") or {}).get("type")),
        }
        # Written only when they say something, matching the bundle: 1,891 items
        # would otherwise carry `legalInGame: true` and a null twin for nothing.
        if entry.get("legalInGame") is False:
            row["legalInGame"] = False
        twin = entry.get("liveTwin")
        if twin:
            # The id only. A `liveTwinName` beside it would be identical to
            # `name` on every row *by construction* — the twin is chosen because
            # it shares the display name — so it would read as a second fact and
            # be a restatement of the first.
            row["liveTwin"] = twin
        out.append(row)
    return out


def max_stack(item_id: str) -> int:
    """
    The game's real stack ceiling, or 0 if unknown.

    saveedit currently infers a ceiling from the largest stack present in the
    save. This is the authoritative figure, but swapping it in changes what a
    sort writes, so that is a deliberate change and not a drive-by one.
    """
    entry = item(item_id)
    return int(entry.get("maxStack") or 0) if entry else 0


# ─── Pals ────────────────────────────────────────────────────────


def normalise_species(species_id: str) -> tuple[str, list[str]]:
    """Strip BOSS_/PREDATOR_/etc, returning (species, prefixes_found)."""
    remaining = str(species_id or "")
    found: list[str] = []
    changed = True
    while changed:
        changed = False
        for prefix in _SPECIES_PREFIXES:
            if remaining.upper().startswith(prefix):
                found.append(prefix.rstrip("_"))
                remaining = remaining[len(prefix):]
                changed = True
    return remaining, found


def pal(species_id: str) -> Optional[dict]:
    species, _ = normalise_species(species_id)
    return _lookup("pals", species)


def pal_exact(species_id: str) -> Optional[dict]:
    """
    A species' own entry, **without** stripping `BOSS_` and friends.

    `pal()` normalises, which is right for naming — an alpha Lamball is still
    called Lamball — and wrong for anything that reads the numbers, because the
    prefixed forms carry their own, higher, stat scaling. `BOSS_Alpaca` has hp
    108 where `Alpaca` has 90, and that difference *is* the alpha bonus. Look up
    the base species and the bonus silently disappears; apply a separate boss
    multiplier on top of the base and it gets counted twice.

    Falls back to the normalised lookup, so a form present in a save but absent
    from the tables still resolves to something rather than to nothing.
    """
    return _lookup("pals", species_id) or pal(species_id)


def pal_exp_table() -> dict[str, Any]:
    """
    The game's own level -> EXP table. `{}` if the bundle is unavailable.

    Two columns per level, and picking the wrong one is easy: `PalNextEXP` is
    the Pal curve and `NextEXP` beside it is the *player* curve. They differ
    from level 2 onwards (25 vs 50).
    """
    return load().get("palExpTable") or {}


def pal_name(species_id: str) -> str:
    """
    A species' display name: **normalised first, exact as a fallback.**

    `pal()` strips `BOSS_`/`RAID_`/… and that is right for naming — an alpha
    Lamball is still called Lamball, and the bundled archive's own
    `(Boss)`/`(Gym)` suffixes are its editorialising rather than the game's
    words. 66 prefixed rows carry one, so preferring the exact row would put
    "Melpaca (Boss)" back on screen everywhere.

    **But 40 prefixed rows have no base row at all**, and those were being
    humanised into nonsense while carrying a perfectly good name of their own:
    `RAID_NightLady_Dark_2` rendered as "Night Lady Dark 2" when its row says
    *Bellanoir Libero (Raid)*, and `RAID_YakushimaBoss002` as "Yakushima
    Boss002" when its row says *Moon Lord*. Stripping `RAID_` looks for
    `NightLady_Dark_2`, which the game does not ship — the raid tiers exist only
    in prefixed form, so the normalising step that rescues alphas is exactly
    what loses these.

    So the fallback order is normalised -> exact -> `humanize`. Reported by an
    operator whose raid tab showed six unnamed bosses beside correctly-named
    summon items.
    """
    entry = pal(species_id)
    if entry and entry.get("name"):
        return entry["name"]
    # No base row. The prefixed row's own name beats humanising the id.
    exact = _lookup("pals", species_id)
    if exact and exact.get("name"):
        return exact["name"]
    species, _ = normalise_species(species_id)
    return humanize(species)


_SKIN_SPLIT = re.compile(r"^(?P<species>.+?)_Skin0*(?P<variant>\d+)$")


def skin_label(skin_id: str) -> Optional[dict[str, Any]]:
    """
    A readable label for an equipped Pal skin, or None.

    **The game ships no display name for these.** `DT_SkinDataTable`'s 29 rows
    have a `SkinName` column that repeats the id, and `item_name` falls through
    to `humanize()` — so "JetDragon_Skin001" was rendering as "Jet Dragon
    Skin001" beside a Pal the dashboard correctly calls Jetragon.

    What the table *does* carry is `TargetPalName`, and the id encodes the same
    species plus a variant number. So the label is **derived**: the species
    resolved through `pal_name`, and the number as the game writes it.
    `derived: true` travels with it, because "Jetragon — Skin 1" is this
    project's phrasing and not Pocketpair's.

    Fails safe. An id that does not match the pattern returns None and the
    caller shows the raw id, which is what it did before.
    """
    match = _SKIN_SPLIT.match(str(skin_id or ""))
    if not match:
        return None
    species = match.group("species")
    name = pal_name(species)
    # `pal_name` humanises an unknown species, which for a skin id would produce
    # the same unreadable string this exists to replace. Only claim a label when
    # the species genuinely resolved.
    if not (pal(species) or _lookup("pals", species)):
        return None
    return {
        "skinId": str(skin_id),
        "speciesId": species,
        "palName": name,
        "variant": int(match.group("variant")),
        "label": f"{name} \u2014 Skin {int(match.group('variant'))}",
        "derived": True,
    }


